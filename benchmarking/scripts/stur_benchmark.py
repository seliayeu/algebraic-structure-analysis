#!/usr/bin/env python3
"""
stur_benchmark.py

Runs the Kalman filter kernel (P1 = A·P0·Aᵀ + Q) generated by StructTensor
across a bandwidth sweep and writes results to a CSV file.

The .stur program is embedded directly in this script so no external file
dependency is needed.

Environment variables:
    STUR_DIR   root of the structtensor project  (default: /app/structtensor)
    RESULTS_DIR directory for output files        (default: ./results)
"""

import csv
import logging
import os
import statistics
import subprocess
import tempfile
from pathlib import Path

logging.basicConfig(level=logging.INFO,
                    format="[%(asctime)s] %(message)s",
                    datefmt="%H:%M:%S")
log = logging.getLogger(__name__)

# ── configuration ─────────────────────────────────────────────────────────────
N          = 1024
BANDWIDTHS = [1023, 512, 256, 128, 64, 32, 16, 0]
WARMUP     = 1
RUNS       = 5

STUR_DIR    = Path(os.environ.get("STUR_DIR",    "/app/structtensor"))
RESULTS_DIR = Path(os.environ.get("RESULTS_DIR", "/results"))

# ── embedded .stur program ────────────────────────────────────────────────────
KALMAN_STUR = """\
symbols: N, X

R1(i, l) := A(i, k) * P0(k, l)
R2(i, j) := R1(i, l) * A(j, l)
P1(i, j) := R2(i, j) + Q(i, j)

A:D(i, k)  := (0 <= i < N) * (0 <= k < N)
P0:D(k, l) := (0 <= k < N) * (0 <= l < N)
Q:D(i, j)  := (0 <= i < N) * (0 <= j < N)
R1:D(i, l) := (0 <= i < N) * (0 <= l < N)
R2:D(i, j) := (0 <= i < N) * (0 <= j < N)
P1:D(i, j) := (0 <= i < N) * (0 <= j < N)

A:U(i, k)  := (i - X <= k) * (k <= i + X)
P0:U(k, l) := (k - X <= l) * (l <= k + X)
Q:U(i, j)  := (i - X <= j) * (j <= i + X)

@preprocess_start
@preprocess_end
"""


def run_cmd(cmd, *, cwd=None):
    result = subprocess.run(
        [str(c) for c in cmd],
        capture_output=True, text=True, cwd=cwd,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"Command failed: {' '.join(str(c) for c in cmd)}\n"
            f"STDERR: {result.stderr[:3000]}"
        )
    return result.stdout


def build_kernel(tmp: Path) -> Path:
    """Generate C++ via structtensor, compile with clang++, return exe path."""
    stur_file = tmp / "kalman.stur"
    cpp_file  = tmp / "kalman.cpp"
    exe       = tmp / "kalman"

    stur_file.write_text(KALMAN_STUR)

    sbt = STUR_DIR.parent / "sbt" / "bin" / "sbt"
    if not sbt.is_file():
        import shutil
        sbt = shutil.which("sbt") or "/opt/sbt/bin/sbt"

    log.info("[stur] generating C++ via structtensor")
    run_cmd(
        [sbt,
         f"runMain uk.ac.ed.dal.structtensor.Main "
         f"-i {stur_file} -o {cpp_file} --init-tensors --only-computation"],
        cwd=STUR_DIR,
    )

    import shutil as _shutil
    clang = _shutil.which("clang++-20") or _shutil.which("clang++") or "clang++"

    log.info("[stur] compiling kernel")
    run_cmd([clang, "-O3", "-std=c++17", "-ffast-math", "-march=native",
             cpp_file, "-o", exe])

    return exe


def run_kernel(exe: Path, bw: int) -> float:
    """Run the compiled kernel at the given bandwidth. Returns mean time in ms."""
    cmd = [str(exe), str(N), str(bw)]

    for _ in range(WARMUP):
        subprocess.run(cmd, capture_output=True)

    times_us = []
    for _ in range(RUNS):
        out = subprocess.run(cmd, capture_output=True, text=True)
        times_us.append(int(out.stdout.strip()))

    avg_ms = statistics.mean(times_us) / 1000.0
    log.info(f"  bw={bw:4d}: {avg_ms:.3f} ms")
    return avg_ms


def main():
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="stur_bench_") as tmp_str:
        tmp = Path(tmp_str)
        exe = build_kernel(tmp)

        rows = []
        log.info("[stur] sweeping bandwidths")
        for bw in BANDWIDTHS:
            avg_ms = run_kernel(exe, bw)
            rows.append({"bw": bw, "avg_ms": avg_ms})

    csv_path = RESULTS_DIR / "kalman_stur.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["bw", "avg_ms"])
        w.writeheader()
        for r in rows:
            w.writerow({"bw": r["bw"], "avg_ms": f"{r['avg_ms']:.3f}"})

    log.info(f"\nResults written to {csv_path}")
    log.info(f"\n{'BW':>6}  {'Avg (ms)':>10}")
    log.info("-" * 20)
    for r in rows:
        log.info(f"{r['bw']:>6}  {r['avg_ms']:>10.3f}")


if __name__ == "__main__":
    main()
